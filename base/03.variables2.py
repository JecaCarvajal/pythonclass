#Lista
frutas = ["manzana", "banana", "cereza", "manzana"]
superheroes = ["Batman", "Superman", "Spiderman"]
print(frutas)
cosas = ["Samuel", 18, 3.14, True]
print(cosas)
#Tupla (La direrencia es que la tupla no se puede modificar)
punto = (10, 20, 10)
print(punto)
punto1 = (10, "dsdsd", 10.5, True)
print(punto1)
# Diccionario se compone de una llave y un valor
persona = {"nombre": "Samuel", "edad": 18, "altura": 1.75, "superheroes": superheroes}
print(persona)
# Set (No permite valores duplicados)
frutas_set = set(frutas)
print(frutas_set)
